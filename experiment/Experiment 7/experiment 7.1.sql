DECLARE
    CURSOR emp_cursor IS SELECT EMPLOYEE_ID, SALARY FROM EMPLOYEE;

    V_EMP_ID   EMPLOYEE.EMPLOYEE_ID%TYPE;
    V_SALARY   EMPLOYEE.SALARY%TYPE;
    SALARY_ZERO EXCEPTION;
BEGIN
    OPEN emp_cursor;
    FETCH emp_cursor INTO V_EMP_ID, V_SALARY;
    WHILE emp_cursor%FOUND
    LOOP
        IF V_SALARY = 0 THEN
            RAISE SALARY_ZERO;
        END IF;
        UPDATE EMPLOYEE
        SET SALARY = V_SALARY * 1.10
        WHERE EMPLOYEE_ID = V_EMP_ID;

        FETCH emp_cursor INTO V_EMP_ID, V_SALARY;
    END LOOP;

    CLOSE emp_cursor;

EXCEPTION
    WHEN SALARY_ZERO THEN
        DBMS_OUTPUT.PUT_LINE('Salary is zero. Increment not possible.');
END;
